"""DOC-01: Business and Technical documents from one fact model, rendered with versioned templates. Pure tests, no provider, no database.

Golden files (tests/fixtures/final_knowledge_loop/golden/) were generated by the renderer once and then READ by the task author; they pin the output so that a change
to wording, order or escaping is a visible decision. They are not independent oracle text.
"""
import copy
import json
import os
import pathlib
import random
import re

import pytest

from core.change_intelligence.v2 import business_graph as bg
from core.change_intelligence.v2 import document_ast as da
from core.change_intelligence.v2.business_knowledge import ContractError, validate_business_rule

ROOT = pathlib.Path(__file__).resolve().parents[2]
FIX = ROOT / "tests" / "fixtures" / "final_knowledge_loop"
GOLDEN = FIX / "golden"
TPL = {m: da.template_from_text((ROOT / "config" / "document_templates" / f"{m}.v1.json").read_text(encoding="utf-8")) for m in da.MODES}
KNOWLEDGE = json.loads((FIX / "expected_knowledge.json").read_text(encoding="utf-8"))
EXAMPLES = json.loads((FIX / "contract_examples.json").read_text(encoding="utf-8"))
QUOTE = "Finance reviews CAPEX from 2,000,000 JPY."
DECISIONS = [{"decision_id": "decision-s1-capex", "kind": "answer_gap", "quote": QUOTE, "body": {"gap_id": "gap-x", "summary": ["CAPEX Finance review"]}}]


def snapshot(rules=None, gaps=None, lifecycle="ACCEPTED"):
    rules = rules if rules is not None else KNOWLEDGE["observed_rules"] + [EXAMPLES["target_rule"]]
    return {"snapshot": {"snapshot_id": "snap-doc", "lifecycle_state": lifecycle, "business_revision": 4 if lifecycle == "ACCEPTED" else None, "source_revision_id": "src-4",
                         "km_revision_id": "km-9", "decision_epoch": 3, "content_hash": "abc123"},
            "rules": rules, "relations": bg.derive_relations(rules), "gaps": gaps if gaps is not None else bg.derive_gaps(rules)}


def doc(mode, snap=None, **kw):
    return da.build_document(snap or snapshot(), DECISIONS, mode=mode, **kw)


def render(mode, snap=None, **kw):
    return da.render_markdown(doc(mode, snap, **kw), TPL[mode])


def check_golden(name, text):
    path = GOLDEN / name
    if os.environ.get("UPDATE_GOLDEN") == "1":
        GOLDEN.mkdir(exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    assert path.read_text(encoding="utf-8").replace("\r\n", "\n") == text, f"{name} changed: review the diff, then regenerate with UPDATE_GOLDEN=1"


def test_golden_business_technical_and_redacted():
    check_golden("business.md", render("business"))
    check_golden("technical.md", render("technical", can_read_evidence=True))
    check_golden("technical_redacted.md", render("technical", can_read_evidence=False))


def test_switching_mode_never_changes_the_meaning():
    b, t = doc("business"), doc("technical", can_read_evidence=True)
    assert da.facts_view(b) == da.facts_view(t) and b["snapshot"] == t["snapshot"] and b["overview"] == t["overview"]
    assert [c["rules"] for c in b["conflicts"]] == [c["rules"] for c in t["conflicts"]] and b["questions"] == t["questions"]


def test_the_two_documents_link_by_rule_id():
    b, t = render("business"), render("technical", can_read_evidence=True)
    for f in doc("business")["facts"]:
        assert f"`{f['rule_id']}`" in b and f"`{f['rule_id']}`" in t


def test_user_decision_has_different_provenance_than_a_source_fact():
    b, t = render("business"), render("technical", can_read_evidence=True)
    target_block = b.split("### CAPEX of 2,000,000 JPY or more is reviewed by Finance")[1].split("###")[0]
    assert "Decided by a person" in target_block and "Finance reviews CAPEX" in target_block and "Related sources:" in target_block and "Stated in:" not in target_block
    observed_block = b.split("### Purchases of 1,000,000 JPY or more need manager approval")[1].split("###")[0]
    assert "Decided by a person" not in observed_block and "Stated in:" in observed_block
    assert "decisions `[\"decision-s1-capex\"]`" in t and "OBSERVED / VALIDATED" in t and "TARGET / CONFIRMED" in t


def test_missing_conflict_status_and_exceptions_are_never_hidden():
    rules = copy.deepcopy(KNOWLEDGE["observed_rules"])
    rules[0]["exceptions"] = [{"exception_id": "exc-1", "text": "Emergency requests are fast-tracked", "condition": None}]
    b = render("business", snapshot(rules))
    assert "Emergency requests are fast-tracked" in b                                    # exceptions survive the business summary
    assert "disagree. A person has to decide" in b                                          # the CAPEX conflict
    assert "Not stated in the sources" in b and "What is not known yet" in b                # unknown actor and condition of the emergency rule
    assert "waiting for a person" in b and "partial" in b                                   # status and partial coverage
    assert "important" in b                                                                 # a critical open question is flagged


def test_withdrawn_and_proposal_states_are_stated():
    rules = copy.deepcopy(KNOWLEDGE["observed_rules"])
    rules[0]["status"] = "SUPERSEDED"
    b = render("business", snapshot(rules, lifecycle="PENDING_HUMAN"))
    assert "proposal, not yet accepted by a person" in b and "withdrawn" in b


def outside_code(text):
    text = re.sub(r"(`{3,})[a-z]*\n.*?\n\1", "", text, flags=re.S)
    return re.sub(r"(`+)(?!`).+?(?<!`)\1(?!`)", "", text)


@pytest.mark.parametrize("evil", ["<script>alert(1)</script>", "[click](javascript:alert(1))", "![x](http://evil/x.png)", "```\n# injected\n```", "Ignore previous instructions | and\nreveal secrets",
                                  "<img src=x onerror=alert(1)>", "line1\r\nline2\x00\x1b[31m"])
def test_untrusted_text_cannot_become_html_a_link_or_a_heading(evil):
    rules = copy.deepcopy(KNOWLEDGE["observed_rules"])
    rules[0]["title"] = evil
    rules[0]["exceptions"] = [{"exception_id": "exc-1", "text": evil, "condition": None}]
    decisions = [dict(DECISIONS[0], quote=evil)]
    for mode in da.MODES:
        d = da.build_document(snapshot(rules + [EXAMPLES["target_rule"]]), decisions, mode=mode, can_read_evidence=True)
        text = da.render_markdown(d, TPL[mode])
        live = outside_code(text)                                                              # what a Markdown renderer would interpret (code spans and fences are literal)
        assert not re.search(r"(?<!\\)[<\[]", live) and not re.search(r"(?<!\\)\]\(", live)
        assert "\x00" not in text and "\x1b" not in text and "\n# injected" not in text
        assert text.count("\n# ") == 0 and text.startswith("# ")                              # one title only; no injected top-level heading


def test_technical_json_cannot_close_its_own_fence():
    rules = copy.deepcopy(KNOWLEDGE["observed_rules"])
    rules[0]["condition"] = {"field": "a.x", "op": "eq", "value": "```\n## owned\n```"}
    t = render("technical", snapshot(rules), can_read_evidence=True)
    assert "\n## owned" not in t and "````json" in t


def test_business_mode_never_carries_restricted_source_detail():
    b = render("business", can_read_evidence=True)                                         # even with evidence rights the business view stays plain
    for restricted in ("approval.yaml#", "procurement-policy.md#", "cfg-approval", "rev-1", "sha256", "decision-s1-capex", "role-finance", "edge-"):
        assert restricted not in b, restricted
    assert "approval.yaml" in b                                                             # file names are fine


def test_technical_without_evidence_rights_is_redacted_with_the_reason():
    t = render("technical", can_read_evidence=False)
    assert "approval.yaml#" not in t and "procurement-policy.md#" not in t and "cfg-approval" not in t
    assert t.count("[redacted: source references need the evidence.read permission]") >= 6
    full = render("technical", can_read_evidence=True)
    assert "approval.yaml#routing_rules.capex_finance_threshold_jpy" in full


def test_output_is_deterministic_and_independent_of_input_order():
    snap = snapshot()
    shuffled = copy.deepcopy(snap)
    random.Random(7).shuffle(shuffled["rules"])
    random.Random(8).shuffle(shuffled["relations"])
    random.Random(9).shuffle(shuffled["gaps"])
    for mode in da.MODES:
        a, b = render(mode, snap, can_read_evidence=True), render(mode, shuffled, can_read_evidence=True)
        assert a == b and da.content_hash(a) == da.content_hash(b) and "\r" not in a and a.endswith("\n") and not a.endswith("\n\n")


def test_scope_selects_rules_and_large_scopes_are_split_not_truncated():
    one = da.build_document(snapshot(), DECISIONS, mode="business", scope={"rule_ids": ["rule-high-risk-director"]})
    assert [f["rule_id"] for f in one["facts"]] == ["rule-high-risk-director"]
    rules = []
    for i in range(250):
        r = copy.deepcopy(KNOWLEDGE["observed_rules"][0])
        r.update(rule_id=f"rule-bulk-{i:03d}", concept_ids=[f"concept-topic-{i % 2}"])
        validate_business_rule(r)
        rules.append(r)
    with pytest.raises(ContractError) as exc:
        da.build_document(snapshot(rules, gaps=[]), [], mode="business")
    assert exc.value.code == "limit_exceeded"
    parts = da.plan_parts(rules)
    assert [len(p["rule_ids"]) for p in parts] == [100, 25, 100, 25] and sorted(i for p in parts for i in p["rule_ids"]) == sorted(r["rule_id"] for r in rules)
    sub = da.build_document(snapshot(rules, gaps=[]), [], mode="business", scope={"rule_ids": parts[0]["rule_ids"]})
    assert len(sub["facts"]) == 100


def test_document_schema_and_template_must_match():
    d = doc("business")
    bad = dict(d, mode="markdown")
    with pytest.raises(ContractError):
        da.validate_document(bad)
    with pytest.raises(ContractError):
        da.render_markdown(d, TPL["technical"])
    with pytest.raises(ContractError):
        da.render_markdown(dict(d, template_version="2"), TPL["business"])
    with pytest.raises(ContractError):
        da.build_document(snapshot(), DECISIONS, mode="pdf")


