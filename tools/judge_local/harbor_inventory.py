"""Read-only inventory of the PUBLIC Harbor input tree: what the existing admission + parsers do with each file type.
No database, no network, no model. Reads only `.../harbor_demo/input` (never evaluator_private/authoring/reports).

  python -m tools.judge_local.harbor_inventory [--input <dir>] [--files] [--manifest <out.json>]

`--files` prints one row per file: path, type, size, business role, parser support, content eligibility (generated output, dependency list,
secret-like content, cache are excluded by CONTENT and provenance, not only by name), whether the Pitch workspace imports it and whether the
offline seed analysed it. `--manifest` writes the same as JSON together with the proposed source groups and their worst-case live ceilings
(estimates from the configured per-call token ceilings; nothing here calls a provider or spends anything).
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
_MAIN = REPO.parents[2] if REPO.parent.name == "worktrees" else REPO
DEFAULT = pathlib.Path(__file__).resolve()
for cand in (REPO.parent / "Ripple", _MAIN):
    p = cand / "ripple" / "_testdata" / "generated" / "bundles" / "harbor_demo" / "input"
    if p.is_dir():
        DEFAULT = p
        break


# ---------------------------------------------------------------------------------------------------------------- per-file inventory
PITCH_SCOPE = ("config/approval.yaml", "config/workflow.yaml", "docs/procurement_policy.md", "docs/finance_desk_guide.md", "data/approval_matrix.xlsx", "app/calculations.py")
SEED_ANALYSED = PITCH_SCOPE[:5]                      # the offline seed extracts the first five; calculations.py is imported but not analysed
SECRET_LIKE = re.compile(rb"-----BEGIN [A-Z ]*PRIVATE KEY-----|AKIA[0-9A-Z]{16}|(?i:api[_-]?key|secret|password|token)\s*[:=]\s*['\"]?[A-Za-z0-9/+_\-]{12,}")
# per-call ceilings of the configured candidate (docs/runbooks/pitch_budget_config.yaml): 24000 in / 12288 out, 2 attempts reserved per job
MAX_IN_TOKENS, WORST_JOB_USD = 24000, 0.25632
PROMPT_OVERHEAD_TOKENS = 4000


def business_role(rel: str) -> str:
    p = pathlib.PurePosixPath(rel)
    stem = p.stem.replace("_", " ")
    top = p.parts[0]
    if top == "config":
        return "Approval and workflow settings"
    if top == "docs":
        return {"procurement policy": "Procurement policy", "finance desk guide": "Finance desk guide", "emergency purchases": "Emergency purchase procedure",
                "invoice matching manual": "Invoice matching manual", "data dictionary": "Data dictionary"}.get(stem, f"Operating document: {stem}")
    if top == "app":
        return "Program code that implements the rules"
    if top == "tests":
        return "Tests of the program (a behaviour oracle)"
    if top == "run_output":
        return "Generated output of the program"
    if p.suffix == ".xlsx":
        return "Workbook"
    if p.suffix == ".csv":
        return "Master data"
    if p.suffix == ".jsonl":
        return "Transaction data"
    if p.suffix == ".html":
        return "Document form"
    return "Other"


def eligibility(rel: str, content: bytes) -> tuple[bool, str]:
    """(eligible for knowledge, why not). Decided from provenance AND content, never from a name alone."""
    p = pathlib.PurePosixPath(rel)
    if "__pycache__" in p.parts or p.suffix in (".pyc", ".pyo"):
        return False, "a cache"
    if p.parts[0] == "run_output":
        return False, "generated by the program, not a source of rules"
    if p.name.startswith("requirements") and p.suffix == ".txt":
        return False, "a dependency list"
    if SECRET_LIKE.search(content):
        return False, "contains secret-like content"
    return True, ""


def file_rows(root: pathlib.Path, sia, admit_files) -> list[dict]:
    files = [p for p in sorted(root.rglob("*")) if p.is_file() and "__pycache__" not in p.parts]
    entries = [(("harbor_demo/" + p.relative_to(root).as_posix()), p.read_bytes()) for p in files]
    disp = {i.logical_path: (i.disposition, i.reason) for i in admit_files(entries).items}
    rows = []
    for logical, content in entries:
        rel = logical.split("/", 1)[1]
        d, reason = disp.get(logical, ("?", None))
        parser = sia.parser_for(logical) if d == "admitted" else None
        obs = len(parser(logical, content).observations) if parser else 0
        ok, why = eligibility(rel, content)
        est_tokens = len(content) // 4
        rows.append({"path": rel, "type": pathlib.PurePosixPath(rel).suffix.lower() or "(none)", "bytes": len(content), "business_role": business_role(rel),
                     "parser": "supported" if parser else f"not supported ({reason})", "observations": obs, "eligible": ok, "excluded_because": why,
                     "in_pitch_workspace": rel in PITCH_SCOPE, "analysed_in_seed": rel in SEED_ANALYSED,
                     "ai_analysis_candidate": bool(ok and parser and pathlib.PurePosixPath(rel).suffix.lower() in (".md", ".yaml", ".xlsx", ".py")),
                     "est_input_tokens": est_tokens, "est_calls": max(1, -(-(est_tokens + PROMPT_OVERHEAD_TOKENS) // MAX_IN_TOKENS))})
    return rows


GROUPS = (
    ("G1 Approval and workflow settings", lambda r: r["path"].startswith("config/"), "Already imported and analysed (offline seed). The core of every demo."),
    ("G2 Policy and guide documents", lambda r: r["path"].startswith("docs/") or r["path"] == "README.md", "2 of 9 are in the Pitch workspace; the other documents (emergency, invoice matching, data dictionary...) let a judge ask questions about them."),
    ("G3 Workbooks", lambda r: r["type"] == ".xlsx", "approval_matrix is analysed; procurement_summary and supplier_directory add cross-checks."),
    ("G4 Program code that implements the rules", lambda r: r["path"].startswith("app/"), "Harbor ships this code. Since Python parser 1.1.0 each function, method and class header is a `code_block` observation (original text, exact line span; parsed with `ast`, never executed), so it can carry evidence. The simulation runs a pinned, hash-verified copy."),
    ("G5 Tests of the program", lambda r: r["path"].startswith("tests/"), "Read-only evidence of intended behaviour. Low priority for AI analysis."),
    ("G6 Master and transaction data", lambda r: r["type"] in (".csv", ".jsonl") and not r["path"].startswith("run_output/"), "Input for the simulation, not for rule extraction: import is optional, AI analysis is not planned."),
    ("G7 Excluded by content or provenance", lambda r: not r["eligible"], "Generated output, dependency list, caches or secret-like content."),
    ("G8 Not readable yet", lambda r: r["eligible"] and r["parser"].startswith("not supported"), "HTML forms: no parser is admitted today."),
)


def plan(rows: list[dict]) -> list[dict]:
    out, used = [], set()
    for name, pick, note in GROUPS:
        members = [r for r in rows if pick(r) and r["path"] not in used]
        used |= {r["path"] for r in members}
        cand = [r for r in members if r["ai_analysis_candidate"]]
        calls = sum(r["est_calls"] for r in cand)
        out.append({"group": name, "files": len(members), "bytes": sum(r["bytes"] for r in members), "ai_analysis_files": len(cand), "ai_analysis_calls_estimate": calls,
                    "ai_analysis_worst_case_usd": round(calls * WORST_JOB_USD, 2), "imported_now": sum(1 for r in members if r["in_pitch_workspace"]),
                    "analysed_now": sum(1 for r in members if r["analysed_in_seed"]), "note": note})
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--files", action="store_true")
    ap.add_argument("--manifest", default=None)
    ap.add_argument("--input", default=str(DEFAULT))
    args = ap.parse_args(argv)
    root = pathlib.Path(args.input)
    if not root.is_dir() or root.name != "input" or root.parent.name != "harbor_demo":
        print("refusing: --input must be the public harbor_demo/input directory", file=sys.stderr)
        return 2
    sys.path.insert(0, str(REPO))
    from core.change_intelligence.v2 import source_ingest_adapters as sia
    from core.change_intelligence.v2.source_admission import admit_files

    files = [p for p in sorted(root.rglob("*")) if p.is_file() and "__pycache__" not in p.parts]
    entries = [(("harbor_demo/" + p.relative_to(root).as_posix()), p.read_bytes()) for p in files]
    report = admit_files(entries)
    disp = {i.logical_path: (i.disposition, i.reason) for i in report.items}
    by_ext: dict = collections.defaultdict(lambda: {"files": 0, "bytes": 0, "admitted": 0, "skipped": [], "obs": 0, "diag": 0})
    for logical, content in entries:
        ext = pathlib.PurePosixPath(logical).suffix.lower() or "(none)"
        row = by_ext[ext]
        row["files"] += 1
        row["bytes"] += len(content)
        d, reason = disp.get(logical, ("?", None))
        if d == "admitted":
            row["admitted"] += 1
            parser = sia.parser_for(logical)
            if parser is not None:
                res = parser(logical, content)
                row["obs"] += len(res.observations)
                row["diag"] += len(res.diagnostics)
        else:
            row["skipped"].append(reason)
    print(f"public input: {len(entries)} files (pyc caches excluded); admission batch ok={report is not None}")
    print(f"{'ext':8} {'files':>5} {'bytes':>9} {'admitted':>8} {'observations':>12} {'diag':>5}  skipped-reasons")
    for ext in sorted(by_ext):
        r = by_ext[ext]
        print(f"{ext:8} {r['files']:5d} {r['bytes']:9d} {r['admitted']:8d} {r['obs']:12d} {r['diag']:5d}  {sorted(set(map(str, r['skipped'])))}")
    if args.files or args.manifest:
        rows = file_rows(root, sia, admit_files)
        groups = plan(rows)
        if args.files:
            print()
            for r in rows:
                print(f"{r['path']:44} {r['type']:7} {r['bytes']:7d}  {r['business_role'][:40]:40} {r['parser'][:22]:22} obs={r['observations']:4d} "
                      f"{'ok ' if r['eligible'] else 'EXCL'} imported={int(r['in_pitch_workspace'])} analysed={int(r['analysed_in_seed'])}")
            print()
            for g in groups:
                print(f"{g['group']:46} files={g['files']:3d} ai_files={g['ai_analysis_files']:3d} est_calls={g['ai_analysis_calls_estimate']:3d} worst_case_usd={g['ai_analysis_worst_case_usd']:6.2f}")
        if args.manifest:
            pathlib.Path(args.manifest).write_text(json.dumps({"input": "ripple/_testdata/generated/bundles/harbor_demo/input", "files": rows, "groups": groups,
                                                               "assumptions": {"max_input_tokens_per_call": MAX_IN_TOKENS, "prompt_overhead_tokens": PROMPT_OVERHEAD_TOKENS,
                                                                               "worst_case_usd_per_job": WORST_JOB_USD, "tokens_estimate": "bytes / 4"}}, indent=2), encoding="utf-8")
            print(f"manifest written: {args.manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
