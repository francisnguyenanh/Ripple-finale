"""Job kind "ma.sandbox" (MA-C1, deterministic, 0 provider calls): the validated TYPED test cases of the tester are rendered by the server into one pytest file through a fixed
template (identifiers checked, arguments as JSON scalars; the model never writes code), then run on a disposable clone of the declared repository at the candidate's base: once
without the patch and once with the patch applied, next to the repository's protected declared commands. Advisory isolation exactly as FEX-04 (timed subprocess, output caps,
secret-free environment, throwaway clone); hostile code is out of scope. The result goes into the child row before the join job is created.
"""
from __future__ import annotations

import json
import pathlib
import re
import shutil
import subprocess

from core.change_intelligence.v2 import ma_orchestration as ma
from infra.adapters import v2_ma
from infra.worker import code_change as cc
from infra.worker.execution_types import ExecutionContext, ExecutionOutcome, ExecutionRequest, NonRetryableExecutionError, ProviderCallBudget

EXECUTOR_ID = "ma.sandbox.v1"
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,60}$")
_MODULE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*){0,6}$")
_OPS = {"eq": "==", "ne": "!=", "gt": ">", "gte": ">=", "lt": "<", "lte": "<="}


def render_tests(cases: list, *, run_id: str) -> str:
    """One pytest module from typed cases. Only identifiers that passed the regexes and JSON scalars reach the file (rendered with json.dumps, never str())."""
    lines = ["# generated by Ripple from TYPED test cases proposed by the tester role; the model wrote no code (identifiers and scalars only)", f"# run {run_id}", "import importlib", ""]
    for i, c in enumerate(cases):
        if not (_IDENT.match(c["name"]) and _IDENT.match(c["function"]) and _MODULE.match(c["module"]) and c["expect_op"] in _OPS):
            raise NonRetryableExecutionError("case_identifier_invalid", c.get("name"))
        args = ", ".join(json.dumps(a) for a in c["args"])
        lines += [f"def test_{c['name']}_{i:02d}():", f"    mod = importlib.import_module({json.dumps(c['module'])})",
                  f"    assert getattr(mod, {json.dumps(c['function'])})({args}) {_OPS[c['expect_op']]} {json.dumps(c['expect_value'])}", ""]
    return "\n".join(lines)


def _pytest_outcomes(output: str) -> dict:
    """Which generated tests passed/failed from pytest's -rA summary lines (`PASSED tests/x.py::test_a` / `FAILED ...`)."""
    out = {}
    for m in re.finditer(r"^(PASSED|FAILED|ERROR) [^:]+::(test_\w+)", output, re.M):
        out[m.group(2)] = m.group(1)
    return out


class MaSandboxExecutor:
    external = False
    executor_id = EXECUTOR_ID

    def prepare(self, ctx: ExecutionContext) -> ExecutionRequest:
        p = ctx.job["payload"]
        for key in ("run_id", "child_id", "role", "round", "candidate_job_id"):
            if key not in p:
                raise NonRetryableExecutionError("payload_invalid", key)
        return ExecutionRequest(prompt="", schema=None, provider_calls_planned=0, external=False)

    def execute(self, ctx: ExecutionContext, request: ExecutionRequest, calls: ProviderCallBudget) -> ExecutionOutcome:
        p = ctx.job["payload"]
        tenant, ws = ctx.job["tenant_id"], ctx.job["workspace_id"]
        try:
            result = self._run(ctx, p)
        except BaseException as exc:
            reason = getattr(exc, "reason", None) or type(exc).__name__
            v2_ma.record_child_result(ctx.store, tenant, ws, p["child_id"], status="FAILED", result={"failed": str(reason)[:120], "role": p["role"], "round": p["round"]})
            self._enqueue_join(ctx.store, tenant, ws, p["run_id"], p["child_id"])
            raise
        v2_ma.record_child_result(ctx.store, tenant, ws, p["child_id"], status="COMPLETED", result=result)
        self._enqueue_join(ctx.store, tenant, ws, p["run_id"], p["child_id"])
        return ExecutionOutcome(result=result, model_id=None)

    def _run(self, ctx, p) -> dict:
        run = v2_ma._run(ctx.store, ctx.job["tenant_id"], ctx.job["workspace_id"], p["run_id"])
        if run is None or run["status"] not in ("RUNNING", "JOINING"):
            raise NonRetryableExecutionError("run_not_running", run["status"] if run else "missing")
        cand = cc._completed(ctx, p["candidate_job_id"], "code.candidate", "candidate_not_completed")
        cases = []
        for a in p.get("synthesis_inputs") or []:
            cases += a.get("cases") or []
        repo = cc.repo_config(ctx.job["workspace_id"], cand["repo_id"])
        test_rel = f"tests/test_ripple_generated_{p['run_id'][-8:]}.py"
        rendered = render_tests(cases, run_id=p["run_id"]) if cases else None
        timeout = int(repo.get("timeout_seconds", 180))

        def phase(apply_patch: bool) -> dict:
            checkout = cc.clone(repo["path"], cand["base_sha"])
            try:
                if apply_patch:
                    pf = pathlib.Path(checkout, ".ripple-candidate.patch")
                    pf.write_text(cand["diff"], encoding="utf-8", newline="\n")
                    r = subprocess.run(["git", "apply", "--whitespace=nowarn", str(pf)], cwd=checkout, capture_output=True, text=True, timeout=60)
                    pf.unlink()
                    if r.returncode != 0:
                        raise NonRetryableExecutionError("patch_does_not_apply", r.stderr.strip()[:300])
                out = {"protected": cc.run_commands(checkout, repo["validate"], timeout_seconds=timeout, repo=repo) if repo.get("validate") else {"status": "NOT_RUN", "commands": []}}
                if rendered is not None:
                    tp = pathlib.Path(checkout, test_rel)
                    tp.parent.mkdir(parents=True, exist_ok=True)
                    tp.write_text(rendered, encoding="utf-8", newline="\n")
                    gen = cc.run_commands(checkout, [["{python}", "-m", "pytest", "-q", "-rA", "-p", "no:cacheprovider", test_rel]], timeout_seconds=timeout, repo=repo)
                    out["generated"] = {"status": gen["status"], "outcomes": _pytest_outcomes(gen["commands"][0]["output_tail"]) if gen["commands"] else {}, "commands": gen["commands"]}
                else:
                    out["generated"] = {"status": "NOT_RUN", "outcomes": {}, "commands": []}
                return out
            finally:
                shutil.rmtree(checkout, ignore_errors=True)

        base, patched = phase(False), phase(True)
        rows = []
        for i, c in enumerate(cases):
            key = f"test_{c['name']}_{i:02d}"
            b, pt = base["generated"]["outcomes"].get(key), patched["generated"]["outcomes"].get(key)
            reading = ("distinguishes" if (b == "FAILED" and pt == "PASSED") else "passes_both" if (b == "PASSED" and pt == "PASSED") else "fails_both" if (b == "FAILED" and pt == "FAILED")
                       else "regression" if (b == "PASSED" and pt == "FAILED") else "unknown")
            rows.append({"name": key, "module": c["module"], "function": c["function"], "args": c["args"], "expect": f"{c['expect_op']} {json.dumps(c['expect_value'])}", "base": b, "patched": pt,
                         "reading": reading, "rationale": c.get("rationale")})
        verdict = "review_ready" if patched["protected"]["status"] == "PASSED" else "protected_tests_not_passed" if patched["protected"]["status"] in ("FAILED", "INFRASTRUCTURE_FAILED") else "no_protected_tests"
        return {"executor_id": EXECUTOR_ID, "run_id": p["run_id"], "child_id": p["child_id"], "role": p["role"], "round": p["round"], "kind": "sandbox", "candidate_job_id": p["candidate_job_id"],
                "patch_hash": cand["patch_hash"], "base_sha": cand["base_sha"], "test_file": test_rel if rendered is not None else None, "cases": rows,
                "protected": {"base": base["protected"]["status"], "patched": patched["protected"]["status"], "commands_patched": [{"argv": c["argv"], "exit": c["exit"]} for c in patched["protected"]["commands"]]},
                "generated": {"base": base["generated"]["status"], "patched": patched["generated"]["status"]}, "verdict": verdict, "repairs": 0,
                "isolation": cc.isolation_for(repo), "findings": [], "rejected": [], "disputes": [], "rejected_disputes": [], "notes": [], "status": "OK", "applies_nothing": True}

    @staticmethod
    def on_terminal_without_execution(store, tenant_id, workspace_id, job_id, reason) -> None:
        from infra.worker.ma_specialist import _child_ended_unrun
        _child_ended_unrun(store, tenant_id, workspace_id, job_id, reason)

    @staticmethod
    def _enqueue_join(store, tenant, ws, run_id, child_id) -> None:
        from infra.worker.verification import ensure_job
        try:
            ensure_job(store, tenant, ws, ma.join_job_id(run_id, child_id), v2_ma.KIND_JOIN, {"run_id": run_id, "after": child_id})
        except Exception:
            pass
